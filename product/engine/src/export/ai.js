// AI rule files: DESIGN_SYSTEM.md (index) + one rulebook per foundation, written from generated values.
import { cssName } from './css.js';
import { colorContract, colorRulesMd } from './ai-color.js';
import { typeContract, typeRulesMd } from './ai-type.js';
import { spaceContract, spaceRulesMd } from './ai-space.js';
import { layoutContract, layoutRulesMd } from './ai-layout.js';
import { radiusContract, radiusRulesMd } from './ai-radius.js';
import { borderContract, borderRulesMd } from './ai-border.js';
import { elevationContract, elevationRulesMd } from './ai-elevation.js';
import { motionContract, motionRulesMd } from './ai-motion.js';

const code = (s) => `\`${s}\``;
const table = (head, rows) => `| ${head.join(' | ')} |\n|${head.map(() => '---').join('|')}|\n${rows.map((r) => `| ${r.join(' | ')} |`).join('\n')}\n`;

export function toAiFiles(sys, cfg, report) {
  const p = cfg.prefix;
  const r = (path, ctx) => sys.resolve(path, ctx);
  const files = {};
  const semantic = (prefix) => sys.byPrefix(prefix).filter((t) => t.collection !== 'Primitives');

  // ---------- Colour ----------
  {
    const contract = colorContract(sys, cfg, report);
    files['rules/color.md'] = colorRulesMd(contract);
    files['color.contract.json'] = contract;
  }

  // ---------- Typography ----------
  {
    const contract = typeContract(sys, cfg, report);
    files['rules/typography.md'] = typeRulesMd(contract);
    files['typography.contract.json'] = contract;
  }

  // ---------- Spacing ----------
  {
    const contract = spaceContract(sys, cfg, report);
    files['rules/spacing.md'] = spaceRulesMd(contract);
    files['spacing.contract.json'] = contract;
  }

  // ---------- Layout ----------
  {
    const contract = layoutContract(sys, cfg, report);
    files['rules/layout.md'] = layoutRulesMd(contract);
    files['layout.contract.json'] = contract;
  }

  // ---------- Radius ----------
  {
    const contract = radiusContract(sys, cfg, report);
    files['rules/radius.md'] = radiusRulesMd(contract);
    files['radius.contract.json'] = contract;
  }

  // ---------- Border ----------
  {
    const contract = borderContract(sys, cfg, report);
    files['rules/border.md'] = borderRulesMd(contract);
    files['border.contract.json'] = contract;
  }

  // ---------- Elevation ----------
  {
    const contract = elevationContract(sys, cfg, report);
    files['rules/elevation.md'] = elevationRulesMd(contract);
    files['elevation.contract.json'] = contract;
  }

  // ---------- Motion ----------
  {
    const contract = motionContract(sys, cfg, report);
    files['rules/motion.md'] = motionRulesMd(contract);
    files['motion.contract.json'] = contract;
  }

  // ---------- Index ----------
  {
    const passed = report.checks.filter((c) => c.status === 'pass').length;
    let md = `# ${sys.name} design system — read this first\n\nAccessible-by-design foundations for any product (WCAG 2.2 AA). Generated by ds-engine; values are computed, not hand-picked.\n\n`;
    md += `## How to use these tokens\n1. Use **semantic** tokens only. Primitives (${code('color.blue.60')}, ${code('space.4')} …) exist to feed semantic tokens.\n2. Modes are switched, not renamed: theme (light/dark), density (comfortable/default/compact, on <html> or any container), radius style (sharp/default/round, on <html> or any container), breakpoint (sm–xl), motion (full/reduced).\n3. If a rule below conflicts with a request, follow the rule and say why.\n\n`;
    md += `## Rulebooks\n- [Colour](rules/color.md) (machine-readable: color.contract.json)\n- [Typography](rules/typography.md) (machine-readable: typography.contract.json)\n- [Spacing](rules/spacing.md) (machine-readable: spacing.contract.json)\n- [Layout](rules/layout.md) (machine-readable: layout.contract.json)\n- [Radius](rules/radius.md) (machine-readable: radius.contract.json)\n- [Border](rules/border.md) (machine-readable: border.contract.json)\n- [Elevation](rules/elevation.md) (machine-readable: elevation.contract.json)\n- [Motion](rules/motion.md) (machine-readable: motion.contract.json)\n\n`;
    md += `## Build checks\n${passed} of ${report.checks.length} checks pass; blocking failures: ${report.blocking.length ? report.blocking.join(', ') : 'none'}. See report.html.\n\n`;
    md += table(['Check', 'WCAG', 'Level', 'Result'], report.checks.map((c) => [`${c.id} ${c.title}`, c.wcag, c.level, `${c.status} (${c.summary})`]));
    files['DESIGN_SYSTEM.md'] = md;
  }
  return files;
}
