// CSS custom properties. Aliases become var() references so links survive in code.
// Put data-theme on <html>. data-density, data-radius and data-motion work on <html> or on any container (a dense table in a default page).
import { isAlias, aliasTarget } from '../system.js';
import { BREAKPOINT_MIN, DRAWER_STRIP, STICKY_FROM_EM, spansFor, SPANS } from '../foundations/layout.js';
import { BREAKPOINTS } from '../foundations/typography.js';
import { pulseFloor } from '../foundations/motion.js';
import { contrast, composite } from '../color-math.js';

export const cssName = (prefix, path) => `--${prefix}-${path.replace(/\./g, '-')}`;

function cssValue(sys, prefix, t, v, ctx) {
  const ref = (x) => (isAlias(x) ? `var(${cssName(prefix, aliasTarget(x))})` : null);
  // A px value that must also grow with the reader's text size: never less than the px value, more at bigger text.
  if (isAlias(v) && t.meta?.growsWithText) return `max(${ref(v)}, ${sys.resolve(t.path, ctx) / 16}rem)`;
  if (isAlias(v)) return ref(v);
  switch (t.type) {
    case 'dimension':
      if (t.path.startsWith('font.size.') || t.meta?.rem) return `${v / 16}rem`;
      return v === 0 ? '0' : `${v}px`;
    case 'duration': return `${v}ms`;
    case 'letterSpacing': return v === 0 ? '0' : `${v}em`;
    case 'cubicBezier': return `cubic-bezier(${v.join(', ')})`;
    case 'shadow': return `${v.offsetX}px ${v.offsetY}px ${v.blur}px ${v.spread}px ${ref(v.color) ?? v.color}`;
    default: return String(v);
  }
}

/** Typography composites expand to one property per field. */
function decls(sys, prefix, t, mode) {
  const v = t.values[mode];
  const ctx = { [t.collection]: mode };
  if (t.type === 'typography') {
    const n = cssName(prefix, t.path);
    const size = sys.resolveValue(v.fontSize, ctx);
    return [
      [`${n}-font-family`, `var(${cssName(prefix, aliasTarget(v.fontFamily))})`],
      [`${n}-font-size`, `var(${cssName(prefix, aliasTarget(v.fontSize))})`],
      [`${n}-font-weight`, `var(${cssName(prefix, aliasTarget(v.fontWeight))})`],
      [`${n}-line-height`, String(+(v.lineHeight / size).toFixed(3))],
      [`${n}-letter-spacing`, `var(${cssName(prefix, aliasTarget(v.letterSpacing))})`],
    ];
  }
  return [[cssName(prefix, t.path), cssValue(sys, prefix, t, v, ctx)]];
}

const block = (selector, lines, indent = '') => `${indent}${selector} {\n${lines.map(([k, v]) => `${indent}  ${k}: ${v};`).join('\n')}\n${indent}}\n`;

export function toCss(sys, cfg) {
  const p = cfg.prefix;
  const tokensIn = (col) => [...sys.tokens.values()].filter((t) => t.collection === col);
  const modeDecls = (col, mode) => tokensIn(col).flatMap((t) => decls(sys, p, t, mode));
  const def = cfg.density.default;

  let css = `/* ${sys.name} tokens — generated by ds-engine. Do not edit by hand. */\n`;
  css += `/* Modes: data-theme="light|dark" on <html>; data-density="comfortable|default|compact", data-radius="sharp|default|round" and data-motion="full|reduced" on <html> or on any container. Reduced motion follows prefers-reduced-motion unless data-motion says otherwise (set it only from the reader's own setting). */\n\n`;
  css += block(':root', [
    ...['Primitives', 'Layout', 'Shape', 'Border', 'Elevation'].filter((c) => sys.collections.has(c)).flatMap((c) => modeDecls(c, sys.collections.get(c).modes[0])),
    ...modeDecls('Color', 'Light'),
    ...modeDecls('Responsive', 'sm'),
    ...modeDecls('Density', def),
    ...modeDecls('Motion', 'full'),
    ['color-scheme', 'light'],
  ]);
  const dark = [...modeDecls('Color', 'Dark'), ['color-scheme', 'dark']];
  css += `\n@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', dark, '  ')}}\n`;
  css += block(':root[data-theme="dark"]', dark);
  css += block(':root[data-theme="light"]', [...modeDecls('Color', 'Light'), ['color-scheme', 'light']]);
  // Breakpoints in em (the same numbers as Tailwind's rem breakpoints): a reader who sets a bigger default text size
  // gets the layout of a narrower screen, with more room per column.
  for (const bp of ['md', 'lg', 'xl']) {
    css += `\n@media (min-width: ${BREAKPOINT_MIN[bp] / 16}em) {\n${block(':root', modeDecls('Responsive', bp), '  ')}}\n`;
  }
  // Density on any element: the spacing variables are redefined there, and everything inside follows.
  for (const d of sys.collections.get('Density').modes) css += block(`[data-density="${d}"]`, modeDecls('Density', d));
  // Radius style on any element: the shape roles are redefined there (the product's style is on :root already).
  for (const st of sys.collections.get('Shape').modes) css += block(`[data-radius="${st}"]`, modeDecls('Shape', st));
  const reduced = modeDecls('Motion', 'reduced');
  css += `\n@media (prefers-reduced-motion: reduce) {\n${block(':root:not([data-motion="full"])', reduced, '  ')}}\n`;
  // data-motion works on any element (a preview of reduced motion inside a page); on <html> it is the reader's own setting.
  css += block('[data-motion="reduced"]', reduced);
  css += block('[data-motion="full"]', modeDecls('Motion', 'full'));

  // Small base layer: the rules that make the tokens do their accessibility job. It is the layer named "base", so
  // with Tailwind v4 it joins Tailwind's own base layer (after Preflight) and utilities still win; without Tailwind,
  // any unlayered app CSS wins. Either way these are defaults, never overrides.
  const v = (path) => `var(${cssName(p, path)})`;
  css += `\n@layer base {\n`;
  // The scroll padding clears the header and the focus ring above a focused item (found by the radius audit: a focused
  // scroll container landed right under the header, its ring's top edge hidden).
  css += `  html { scroll-padding-top: calc(${v('layout.scroll-padding.top')} + ${v('focus.ring.offset')} + ${v('focus.ring.width')}); background: ${v('color.bg.canvas')}; color: ${v('color.fg.default')}; }\n`;
  css += `  :focus-visible { outline: ${v('focus.ring.width')} solid ${v('focus.ring.color')}; outline-offset: ${v('focus.ring.offset')}; }\n`;
  // Forced colours (Windows contrast themes) replace every colour and remove shadows and background images. Borders and
  // outlines survive, so the ring takes the system's highlight; states shown by a fill get an outline in SelectedItem;
  // disabled controls turn GrayText. The state outline sits inside the element, so it never moves layout.
  // Radio choices drawn as labels (segmented controls, choice cards) count too: their selected fill is replaced as well.
  const states = ['[aria-selected="true"]', '[aria-current]:not([aria-current="false"])', '[aria-pressed="true"]', '[aria-checked="true"]:not(input)', 'label:has(> input[type="radio"]:checked)'];
  css += `  @media (forced-colors: active) {\n`;
  css += `    ${states.join(', ')} { outline: ${v('border.width.state')} solid SelectedItem; outline-offset: calc(-1 * ${v('border.width.state')}); }\n`;
  css += `    :focus-visible, ${states.slice(0, 4).map((x) => `${x}:focus-visible`).join(', ')} { outline: ${v('focus.ring.width')} solid Highlight; outline-color: Highlight; outline-offset: ${v('focus.ring.offset')}; }\n`;
  css += `    :disabled, [aria-disabled="true"] { color: GrayText; border-color: GrayText; }\n`;
  css += `  }\n`;
  css += `  a { color: ${v('color.fg.link')}; text-decoration: underline; text-underline-offset: 0.15em; }\n`;
  css += `  a:hover { color: ${v('color.fg.link-hover')}; }\n`;
  // Type defaults: the page reads in body.md; headings get heading styles; form controls inherit the page font
  // (browsers otherwise shrink them to ~13px); numbers in tables line up.
  const ts = (path) => { const n = cssName(p, path); return `font-family: var(${n}-font-family); font-size: var(${n}-font-size); font-weight: var(${n}-font-weight); line-height: var(${n}-line-height); letter-spacing: var(${n}-letter-spacing);`; };
  css += `  body { ${ts('type.body.md')} overflow-wrap: break-word; }\n`;
  for (const [h, path] of [['h1', 'type.heading.lg'], ['h2', 'type.heading.md'], ['h3', 'type.heading.sm'], ['h4', 'type.title.lg'], ['h5, h6', 'type.title.md']]) css += `  ${h} { ${ts(path)} }\n`;
  css += `  strong, b { font-weight: ${v('font.weight.semibold')}; }\n`;
  css += `  code, kbd, samp, pre { font-family: ${v('font.family.mono')}; }\n`;
  css += `  button, input, select, textarea { font: inherit; letter-spacing: inherit; }\n`;
  css += `  td, th, output, data { font-variant-numeric: tabular-nums; }\n`;
  css += `}\n`;

  // Text-style utility classes.
  css += `\n/* Text styles */\n`;
  for (const t of sys.byPrefix('type.')) {
    const n = cssName(p, t.path);
    css += `.${p}-${t.path.replace(/\./g, '-')} { font-family: var(${n}-font-family); font-size: var(${n}-font-size); font-weight: var(${n}-font-weight); line-height: var(${n}-line-height); letter-spacing: var(${n}-letter-spacing);${t.meta.tabular ? ' font-variant-numeric: tabular-nums;' : ''}${t.meta.upper ? ' text-transform: uppercase;' : ''} }\n`;
  }
  // Layout helpers: the layouts every product needs, with the parts people forget built in (items that can shrink,
  // tiles that fit a 320px screen, padding inside the cap, grids that follow their region).
  if (sys.tokens.has('layout.container.max')) css += layoutCss(sys, p, modeDecls, v);
  css += joinCss(p);
  if (sys.tokens.has('layer.sticky')) css += elevationCss(sys, p, v);
  if (sys.tokens.has('motion.floating.duration')) css += motionCss(sys, p, v);
  return css;
}

/**
 * Layout helpers and the app shell. Panes go inline at the breakpoint each one declares — the breakpoint check L3 proved
 * they fit at — and below it a start pane is a drawer (hidden until the app sets data-open) and an end pane sits below
 * the main region. Shell regions are size containers, so a .{p}-grid inside one takes the columns and gutter of the
 * region's own width. DOM order: header, start panes, main, end panes — the visual order never contradicts it.
 */
function layoutCss(sys, p, modeDecls, v) {
  const em = (bp) => `${BREAKPOINT_MIN[bp] / 16}em`;
  const panes = [...sys.tokens.values()].filter((t) => t.meta.layout === 'pane').map((t) => ({ job: t.path.split('.')[2], path: t.path, ...t.meta }));
  const S = `.${p}-shell`;
  let css = `\n/* Layout */\n`;
  css += `.${p}-page { box-sizing: border-box; width: 100%; max-width: calc(${v('layout.container.max')} + 2 * ${v('layout.margin')}); margin-inline: auto; padding-inline: ${v('layout.margin')}; }\n`;
  css += `.${p}-grid { display: grid; grid-template-columns: repeat(${v('layout.columns')}, minmax(0, 1fr)); column-gap: ${v('layout.gutter')}; }\n`;
  css += `.${p}-grid > * { min-width: 0; }\n`;
  css += `.${p}-measure { max-width: ${v('layout.measure.reading')}; }\n`;
  css += `.${p}-tiles { display: grid; grid-template-columns: repeat(auto-fill, minmax(min(100%, ${v('layout.tile.min')}), 1fr)); gap: ${v('space.stack.lg')} ${v('space.inline.lg')}; }\n`;
  css += `.${p}-tiles > * { min-width: 0; }\n`;
  // Spans by fraction, computed from each breakpoint's columns: a card that is "a third" stays a third of whatever grid
  // it is in. Set with the window's breakpoint on :root and with the region's width inside a region.
  const spanDecls = (bp) => Object.entries(spansFor(sys.resolve('layout.columns', { Responsive: bp }))).filter(([k]) => k !== 'full').map(([k, n]) => [`--${p}-span-${k}`, String(n)]);
  css += block(':root', spanDecls('sm'));
  for (const bp of BREAKPOINTS.slice(1)) css += `@media (min-width: ${em(bp)}) {\n${block(':root', spanDecls(bp), '  ')}}\n`;
  css += `.${p}-span-full { grid-column: 1 / -1; }\n`;
  for (const k of SPANS.filter((x) => x !== 'full')) css += `.${p}-span-${k} { grid-column: span var(--${p}-span-${k}); }\n`;
  // Regions: a grid inside takes the grid of the region's width (the same breakpoints, measured on the region).
  const grid = (bp) => [...modeDecls('Responsive', bp).filter(([k]) => k === cssName(p, 'layout.columns') || k === cssName(p, 'layout.gutter')), ...spanDecls(bp)];
  css += `\n/* Regions: a grid follows the region it sits in, not the window */\n`;
  css += `.${p}-region, ${S} > [data-shell]:not([data-shell="header"]) { container: ${p}-region / inline-size; }\n`;
  for (const bp of BREAKPOINTS) css += `@container ${p}-region (min-width: ${bp === 'sm' ? '0' : em(bp)}) {\n${block(`.${p}-grid`, grid(bp), '  ')}}\n`;
  // The shell at each breakpoint where the set of inline panes changes.
  const at = (bp) => panes.filter((x) => BREAKPOINTS.indexOf(x.from) <= BREAKPOINTS.indexOf(bp));
  const areas = (bp) => {
    const inl = at(bp), starts = inl.filter((x) => x.side === 'start'), ends = inl.filter((x) => x.side === 'end');
    const flow = panes.filter((x) => !inl.includes(x) && x.below === 'flow');
    const names = [...starts.map((x) => x.job), 'main', ...ends.map((x) => x.job)];
    const rows = [names.map(() => 'header'), names, ...flow.map((f) => names.map((n) => (n === 'main' ? f.job : n)))];
    // auto tracks sized by the pane itself: a page that leaves a pane out gets no empty column.
    return { cols: [...starts.map(() => 'auto'), 'minmax(0, 1fr)', ...ends.map(() => 'auto')].join(' '), rows: rows.map((r) => `"${r.join(' ')}"`).join(' ') };
  };
  css += `\n/* App shell: <div class="${p}-shell"> with children data-shell="header", the start panes (nav), "main", the end panes (aside) — in that order */\n`;
  const a0 = areas('sm');
  css += `${S} { display: grid; grid-template-columns: ${a0.cols}; grid-template-areas: ${a0.rows}; align-content: start; min-height: 100dvh; }\n`;
  css += `${S} > * { min-width: 0; }\n`;
  css += `${S} > [data-shell="header"] { grid-area: header; z-index: ${v('layer.sticky')}; box-sizing: border-box; min-height: ${v('layout.header.height')}; }\n`;
  // The header sticks only in windows tall enough for it: at 400% zoom, or at 200% text on a laptop, it scrolls away.
  css += `@media (min-height: ${STICKY_FROM_EM}em) {\n  ${S} > [data-shell="header"] { position: sticky; top: 0; }\n}\n`;
  css += `${S} > [data-shell="main"] { grid-area: main; }\n`;
  for (const x of panes) css += `${S} > [data-shell="${x.job}"] { grid-area: ${x.job}; }\n`;
  // Below its breakpoint a drawer pane is out of the grid: hidden (and out of the tab order) until data-open is set.
  for (const x of panes.filter((y) => y.below === 'drawer')) {
    const sel = `${S} > [data-shell="${x.job}"]`;
    css += `${sel} { position: fixed; z-index: ${v('layer.floating')}; inset-block: ${v('layout.header.height')} 0; inset-inline-start: 0; box-sizing: border-box; width: min(${v(x.path)}, 100% - ${DRAWER_STRIP}px); overflow-y: auto; background: ${v('elevation.floating.surface')}; border-inline-end: ${v('border.width.line')} solid ${v('elevation.floating.border')}; box-shadow: ${v('elevation.floating.shadow')}; }\n`;
    css += `${sel}:not([data-open]) { display: none; }\n`;
  }
  let last = JSON.stringify(a0);
  const sticky = [], stickyAt = [];
  for (const bp of BREAKPOINTS.slice(1)) {
    const a = areas(bp);
    const opening = panes.filter((x) => x.from === bp);
    if (JSON.stringify(a) === last && !opening.length) continue;
    last = JSON.stringify(a);
    let inner = block(S, [['grid-template-columns', a.cols], ['grid-template-areas', a.rows]], '  ');
    for (const x of opening) {
      if (x.below === 'drawer') {
        inner += `  ${S} > [data-shell="${x.job}"], ${S} > [data-shell="${x.job}"]:not([data-open]) { display: block; position: static; inset: auto; align-self: start; z-index: auto; box-sizing: border-box; width: ${v(x.path)}; box-shadow: none; }\n`;
        sticky.push(`  ${S} > [data-shell="${x.job}"] { position: sticky; top: ${v('layout.header.height')}; max-height: calc(100dvh - ${v('layout.header.height')}); }\n`);
        stickyAt.push(em(bp));
        inner += `  [data-shell-toggle="${x.job}"] { display: none !important; } /* the drawer's button has no job once the pane is inline */\n`;
      } else inner += `  ${S} > [data-shell="${x.job}"] { box-sizing: border-box; width: ${v(x.path)}; }\n`;
    }
    css += `@media (min-width: ${em(bp)}) {\n${inner}}\n`;
  }
  // Inline navigation stays in view under the sticky header — in the same tall-enough windows.
  sticky.forEach((rule, i) => { css += `@media (min-width: ${stickyAt[i]}) and (min-height: ${STICKY_FROM_EM}em) {\n${rule}}\n`; });
  return css;
}

/**
 * Joined parts (a button group, a segmented control, an input with its button, stacked list items): the outer corners
 * keep their role's radius and the edges where parts meet are square. Logical corners, so the join flips in right-to-left
 * layouts; a focused part is lifted above its neighbours so they can't paint over its ring.
 */
function joinCss(p) {
  const J = `.${p}-join`, md = `${BREAKPOINT_MIN.md / 16}em`;
  // Parts overlap by the control width, so the seam between two bordered parts is one line, not two.
  const over = `calc(-1 * var(--${p}-border-width-control))`;
  const inline = (sel) => `${sel} { flex-direction: row; }\n${sel} > :not(:first-child) { border-start-start-radius: 0; border-end-start-radius: 0; margin-inline-start: ${over}; margin-block-start: 0; }\n${sel} > :not(:last-child) { border-start-end-radius: 0; border-end-end-radius: 0; }\n`;
  const block = (sel) => `${sel} { flex-direction: column; }\n${sel} > :not(:first-child) { border-start-start-radius: 0; border-start-end-radius: 0; margin-block-start: ${over}; margin-inline-start: 0; }\n${sel} > :not(:last-child) { border-end-start-radius: 0; border-end-end-radius: 0; }\n`;
  let css = `\n/* Joined parts: <div class="${p}-join"> side by side, data-join="block" stacked, data-join="auto" stacked until md (a row of parts that can't fit a phone at 200% text). Outer corners keep their shape; shared edges are square; parts overlap by one control border, so every seam is one line. */\n`;
  css += `${J} { display: flex; max-inline-size: 100%; }\n${J} > * { min-inline-size: 0; } /* parts shrink and their labels wrap inside them */\n`;
  css += inline(`${J}:not([data-join])`) + block(`${J}[data-join="block"]`);
  css += `@media not all and (min-width: ${md}) {\n${block(`${J}[data-join="auto"]`).replace(/^/gm, '  ').trimEnd()}\n}\n`;
  css += `@media (min-width: ${md}) {\n${inline(`${J}[data-join="auto"]`).replace(/^/gm, '  ').trimEnd()}\n}\n`;
  // The part that changes is lifted so its whole border shows over the overlap; the focused part goes on top of that.
  css += `${J} > :hover, ${J} > [aria-pressed="true"], ${J} > [aria-selected="true"], ${J} > [aria-current]:not([aria-current="false"]), ${J} > :checked, ${J} > [aria-invalid="true"] { position: relative; z-index: 1; }\n`;
  css += `${J} > :focus-visible, ${J} > :focus-within { position: relative; z-index: 2; }\n`;
  return css;
}

/**
 * Elevation: one class per level, carrying the whole level — surface, shadow, edge and layer — so a component can't take
 * the shadow and forget the edge. Floating and modal levels work with the browser's top layer: a [popover] or a <dialog>
 * opened with showModal() sits above every z-index; the layer numbers order everything else. The scrim is the dialog's
 * ::backdrop. Shadows are removed in forced colours; the borders stay, drawn in the system text colour.
 */
function elevationCss(sys, p, v) {
  const has = (x) => sys.tokens.has(x);
  const line = v('border.width.line');
  let css = `\n/* Elevation: .${p}-raised, .${p}-sticky, .${p}-floating, .${p}-modal, .${p}-dragging. Each class is the whole level: surface, shadow, edge and layer. */\n`;
  css += `.${p}-raised { background: ${v('elevation.raised.surface')}; box-shadow: ${v('elevation.raised.shadow')}; }\n`;
  css += `.${p}-sticky { position: sticky; inset-block-start: 0; z-index: ${v('layer.sticky')}; background: ${v('elevation.sticky.surface')}; box-shadow: ${v('elevation.sticky.shadow')}; border-block-end: ${line} solid ${v('elevation.sticky.border')}; }\n`;
  css += `.${p}-sticky[data-stick="end"] { inset-block: auto 0; border-block-end: 0; border-block-start: ${line} solid ${v('elevation.sticky.border')}; }\n`;
  css += `.${p}-floating { z-index: ${v('layer.floating')}; background: ${v('elevation.floating.surface')}; box-shadow: ${v('elevation.floating.shadow')}; border: ${line} solid ${v('elevation.floating.border')}; color: ${v('color.fg.default')}; }\n`;
  if (has('layer.toast')) css += `.${p}-floating[data-layer="toast"] { z-index: ${v('layer.toast')}; }\n`;
  css += `.${p}-modal { z-index: ${v('layer.modal')}; background: ${v('elevation.modal.surface')}; box-shadow: ${v('elevation.modal.shadow')}; border: ${line} solid ${v('elevation.modal.border')}; color: ${v('color.fg.default')}; }\n`;
  css += `.${p}-modal::backdrop { background: ${v('elevation.modal.scrim')}; }\n`;
  css += `.${p}-scrim { position: fixed; inset: 0; z-index: ${v('layer.modal')}; background: ${v('elevation.modal.scrim')}; } /* for a modal that is not a <dialog>: put it just before the dialog, inside the same layer */\n`;
  css += `.${p}-dragging { position: relative; z-index: ${v('layer.dragging')}; box-shadow: ${v('elevation.dragging.shadow')}; border: ${line} solid ${v('elevation.dragging.border')}; cursor: grabbing; }\n`;
  // Product layers: a class per layer is not needed; they are z-index values (var(--{p}-layer-<job>)).
  return css;
}

/**
 * Motion: ready transitions for everything that opens and closes over the page, using the jobs of the same names —
 * popovers (.{p}-floating[popover]: menus, popovers, tooltips), toasts (data-layer="toast", from the edge they sit on),
 * dialogs (dialog.{p}-modal opened with showModal(), the scrim fading with them) and the navigation drawer (from its own
 * side). Entries use the job's duration and curve; exits its exit duration and curve; display and overlay transition
 * with allow-discrete so a closing popover or dialog stays shown, in the top layer, until it has faded. Movement is
 * always the job's distance, which reduced motion sets to 0 — so in reduced motion everything here only fades, in
 * 100ms. Browsers without @starting-style or allow-discrete simply open and close at once.
 * Two helpers: .{p}-loading (turns while work runs; pulses slowly in reduced motion) and .{p}-highlight (a tint that
 * fades once when something changed on its own).
 */
function motionCss(sys, p, v) {
  const job = (j, part) => v(`motion.${j}.${part}`);
  const up = (j) => `calc(-1 * ${job(j, 'distance')})`;
  const enterExit = (sel, openSel, from, j, extra = '') => {
    let css = `${sel} {${extra} opacity: 0; translate: ${from}; transition-property: opacity, translate, overlay, display; transition-duration: ${job(j, 'exit-duration')}; transition-timing-function: ${job(j, 'exit-easing')}; transition-behavior: allow-discrete; }\n`;
    css += `${openSel} { opacity: 1; translate: none; transition-duration: ${job(j, 'duration')}; transition-timing-function: ${job(j, 'easing')}; }\n`;
    css += `@starting-style {\n  ${openSel} { opacity: 0; translate: ${from}; }\n}\n`;
    return css;
  };
  let css = `\n/* Motion: ready transitions for what opens and closes (motion.floating, motion.modal), .${p}-loading and .${p}-highlight. In reduced motion every distance is 0: they only fade. */\n`;
  // Floating: menus, popovers, tooltips drop in from their trigger, above them.
  css += enterExit(`.${p}-floating[popover]`, `.${p}-floating[popover]:popover-open`, `0 ${up('floating')}`, 'floating');
  // Toasts come up from the edge they sit on (the bottom by default).
  css += `.${p}-floating[popover][data-layer="toast"] { translate: 0 ${job('floating', 'distance')}; }\n`;
  css += `.${p}-floating[popover][data-layer="toast"]:popover-open { translate: none; }\n`;
  css += `@starting-style {\n  .${p}-floating[popover][data-layer="toast"]:popover-open { translate: 0 ${job('floating', 'distance')}; }\n}\n`;
  // Modal: dialogs rise into place; the scrim fades with them.
  css += enterExit(`dialog.${p}-modal`, `dialog.${p}-modal[open]`, `0 ${job('modal', 'distance')}`, 'modal');
  css += `dialog.${p}-modal::backdrop { opacity: 0; transition-property: opacity, overlay, display; transition-duration: ${job('modal', 'exit-duration')}; transition-timing-function: ${job('modal', 'exit-easing')}; transition-behavior: allow-discrete; }\n`;
  css += `dialog.${p}-modal[open]::backdrop { opacity: 1; transition-duration: ${job('modal', 'duration')}; transition-timing-function: ${job('modal', 'easing')}; }\n`;
  css += `@starting-style {\n  dialog.${p}-modal[open]::backdrop { opacity: 0; }\n}\n`;
  css += `.${p}-scrim { transition: opacity ${job('modal', 'duration')} ${job('modal', 'easing')}; }\n@starting-style {\n  .${p}-scrim { opacity: 0; }\n}\n`;
  // The navigation drawer: in from its own side (the start side; flipped right to left), out the same way.
  const S = `.${p}-shell`;
  for (const t of [...sys.tokens.values()].filter((x) => x.meta.layout === 'pane' && x.meta.below === 'drawer')) {
    const pane = t.path.split('.')[2], sel = `${S} > [data-shell="${pane}"]`;
    css += `${sel} { transition-property: opacity, translate, display; transition-duration: ${job('floating', 'exit-duration')}; transition-timing-function: ${job('floating', 'exit-easing')}; transition-behavior: allow-discrete; }\n`;
    css += `${sel}:not([data-open]) { opacity: 0; translate: ${up('floating')} 0; }\n${sel}:dir(rtl):not([data-open]) { translate: ${job('floating', 'distance')} 0; }\n`;
    css += `${sel}[data-open] { transition-duration: ${job('floating', 'duration')}; transition-timing-function: ${job('floating', 'easing')}; }\n`;
    css += `@starting-style {\n  ${sel}[data-open] { opacity: 0; translate: ${up('floating')} 0; }\n  ${sel}[data-open]:dir(rtl) { translate: ${job('floating', 'distance')} 0; }\n}\n`;
    css += `@media (min-width: ${BREAKPOINT_MIN[t.meta.from] / 16}em) {\n  ${sel}, ${sel}:not([data-open]), ${sel}:dir(rtl):not([data-open]) { opacity: 1; translate: none; transition: none; } /* inline from here: it no longer opens */\n}\n`;
  }
  // Loading: one turn per cycle while work runs; in reduced motion a slow pulse that never drops below 3:1.
  const dim = pulseFloor(sys, contrast, composite);
  css += `@keyframes ${p}-spin { to { rotate: 1turn; } }\n@keyframes ${p}-pulse { 50% { opacity: ${dim}; } }\n`;
  css += `.${p}-loading { animation: ${p}-spin ${job('loading', 'duration')} ${job('loading', 'easing')} infinite; }\n`;
  css += `@media (prefers-reduced-motion: reduce) {\n  .${p}-loading:not([data-motion="full"] *) { animation-name: ${p}-pulse; }\n}\n`;
  css += `[data-motion="reduced"] .${p}-loading { animation-name: ${p}-pulse; }\n[data-motion="full"] .${p}-loading { animation-name: ${p}-spin; }\n`;
  // Highlight: a tint that fades once, back to the element's own background.
  css += `@keyframes ${p}-highlight { from { background-color: ${v('color.bg.brand-subtle')}; } }\n`;
  css += `.${p}-highlight { animation: ${p}-highlight ${job('highlight', 'duration')} ${job('highlight', 'easing')}; }\n`;
  return css;
}

/** Layout tokens in Tailwind: spacing utilities (px-margin, gap-x-gutter, min-h-header) and widths (max-w-page, max-w-reading, w-nav …). */
export function layoutTw(path) {
  if (path === 'layout.margin') return { theme: 'spacing', name: 'margin' };
  if (path === 'layout.gutter') return { theme: 'spacing', name: 'gutter' };
  if (path === 'layout.header.height') return { theme: 'spacing', name: 'header' };
  if (path === 'layout.container.max') return { theme: 'container', name: 'page' };
  if (path === 'layout.measure.reading') return { theme: 'container', name: 'reading' };
  if (path === 'layout.tile.min') return { theme: 'container', name: 'tile' };
  if (path.startsWith('layout.pane.')) return { theme: 'container', name: path.split('.')[2] };
  return null;
}

// Size tokens in Tailwind: min-h-control, size-control, gap-icon, min-w-target / min-h-target.
export const SIZE_TW = { 'size.control.height': 'control', 'size.control.icon-gap': 'icon', 'size.target.min': 'target' };

export function toTailwindTheme(sys, cfg) {
  // Tailwind v4: CSS-first theme mapping onto the variables above.
  const p = cfg.prefix;
  // Tailwind's own radius scale (rounded-sm … rounded-4xl) is removed: rounded-* utilities are the ds roles only.
  // Tailwind's own curves (ease-in, ease-out, ease-in-out) and animations (animate-spin, -ping, -pulse, -bounce) are removed:
  // motion comes from the jobs, and .${p}-loading is the only loop. Plain transition utilities default to the feedback job.
  const lines = ['  --radius-*: initial;', '  --shadow-*: initial;', '  --drop-shadow-*: initial;', '  --inset-shadow-*: initial;', '  --ease-*: initial;', '  --animate-*: initial;',
    `  --default-transition-duration: var(${cssName(p, 'motion.feedback.duration')});`, `  --default-transition-timing-function: var(${cssName(p, 'motion.feedback.easing')});`];
  for (const t of sys.tokens.values()) {
    if (t.collection === 'Primitives') continue;
    const n = cssName(p, t.path);
    const tail = t.path.split('.').slice(1).join('-');
    if (t.type === 'color' && t.path.startsWith('color.')) lines.push(`  --color-${tail}: var(${n});`);
    else if (t.path.startsWith('space.')) lines.push(`  --spacing-${tail}: var(${n});`);
    else if (SIZE_TW[t.path]) lines.push(`  --spacing-${SIZE_TW[t.path]}: var(${n});`);
    else if (layoutTw(t.path)) { const l = layoutTw(t.path); lines.push(`  --${l.theme}-${l.name}: var(${n});`); }
    else if (t.path.startsWith('shape.') && !t.path.endsWith('-focus')) lines.push(`  --radius-${tail}: var(${n});`);
    // Border widths by job: border-line, border-b-line, border-control, border-state, border-s-indicator, divide-y-line …
    // Tailwind's bare widths (border, border-2) stay available in Tailwind, but the border checker flags them.
    else if (t.path.startsWith('border.width.') && t.meta.job) lines.push(`  --border-width-${t.meta.job}: var(${n});`);
    // Elevation: shadow-raised … shadow-dragging; Tailwind's own shadow scale (shadow-sm … shadow-2xl) is removed below.
    else if (t.type === 'shadow') lines.push(`  --shadow-${t.path.split('.')[1]}: var(${n});`);
    // Elevation surfaces and edges: bg-elevation-floating-surface, border-elevation-floating-border …
    else if (t.type === 'color' && t.path.startsWith('elevation.')) lines.push(`  --color-${t.path.replace(/\./g, '-')}: var(${n});`);
    // Motion: ease-<job> (and ease-<job>-exit) for the curve; durations as duration-(--ds-motion-<job>-duration).
    else if (t.path.startsWith('motion.') && t.path.endsWith('.easing')) lines.push(`  --ease-${t.path.split('.')[1]}: var(${n});`);
    else if (t.path.startsWith('motion.') && t.path.endsWith('.exit-easing')) lines.push(`  --ease-${t.path.split('.')[1]}-exit: var(${n});`);
  }
  // Type: Tailwind v4 text-* utilities carry size, line height, letter-spacing and weight (text-body-md …).
  // Family, tabular numerals and case are not part of text-*: add font-mono / tabular-nums / uppercase, or use the .${p}-type-* classes.
  lines.push(`  --font-sans: var(${cssName(p, 'font.family.sans')});`, `  --font-mono: var(${cssName(p, 'font.family.mono')});`);
  for (const t of sys.byPrefix('type.')) {
    const n = cssName(p, t.path), tw = t.path.split('.').slice(1).join('-');
    lines.push(`  --text-${tw}: var(${n}-font-size);`, `  --text-${tw}--line-height: var(${n}-line-height);`, `  --text-${tw}--letter-spacing: var(${n}-letter-spacing);`, `  --text-${tw}--font-weight: var(${n}-font-weight);`);
  }
  // Breakpoints: ds's md, lg and xl replace Tailwind's; Tailwind's own sm (40rem) and 2xl (96rem) are removed, so an
  // unprefixed utility is the sm layout and every prefix means the same width as in tokens.css and Figma.
  lines.push(...['md', 'lg', 'xl'].map((bp) => `  --breakpoint-${bp}: ${sys.resolve(`breakpoint.${bp}`) / 16}rem;`), '  --breakpoint-sm: initial;', '  --breakpoint-2xl: initial;');
  return `/* Tailwind v4 theme for ${sys.name}. Import after tokens.css:  @import "tailwindcss"; @import "./tokens.css"; @import "./tailwind.theme.css"; */\n@theme inline {\n${lines.join('\n')}\n}\n`;
}
