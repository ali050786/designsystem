#!/usr/bin/env node
// Elevation checker: finds elevation-rule breaks in CSS, HTML and Tailwind/JSX against the elevation contract.
// Usage: node src/lint/elevation-lint.js <files or folders...> [--contract out/default/ai/elevation.contract.json] [--json]
// Has no dependencies: copy this one file into any project and point --contract at the elevation.contract.json you ship.
// Exit code 1 when any error is found. `ds-lint-ignore: ER-xx` anywhere in a file switches a rule off for that file.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));

export const loadContract = (file) => contractIndex(JSON.parse(fs.readFileSync(file, 'utf8')));

export function contractIndex(c) {
  const levels = c.levels.map((l) => l.job);
  const shadowed = c.levels.filter((l) => l.shadow).map((l) => l.job);
  const floating = c.levels.filter((l) => l.edge && l.edge.sides === 'all').map((l) => l.job);
  const surfaceRole = Object.fromEntries(c.levels.filter((l) => l.surface).map((l) => [l.job, l.surface.role]));
  const layers = c.layers.map((l) => l.name.slice(6));
  return { c, p: c.prefix, levels, known: new Set(levels), shadowed: new Set(shadowed), floating: new Set(floating), surfaceRole, layers: new Set(layers), localZ: new Set(c.limits.localZ) };
}

const lineOf = (text, idx) => text.slice(0, idx).split('\n').length;
const HOVER = /:(hover|active)(?![\w-])/;
const FOCUS = /:(focus|focus-visible|focus-within)(?![\w-])/;
const DARK_SEL = /\[data-theme=["']?dark["']?\]|\.dark(?=$|[\s:.[,#>+~)])/;

function parseDecls(body, baseLine) {
  const out = [];
  let offset = 0;
  for (const part of body.split(';')) {
    const i = part.indexOf(':');
    if (i > 0) out.push({ prop: part.slice(0, i).trim().toLowerCase(), value: part.slice(i + 1).trim().replace(/\s*!important\s*$/, ''), line: baseLine + body.slice(0, offset).split('\n').length - 1 + (part.match(/^\s*\n/) ? part.match(/^\s*/)[0].split('\n').length - 1 : 0) });
    offset += part.length + 1;
  }
  return out;
}

/** Index ranges of @media blocks whose condition matches `test` (brace-matched, so nested rules are inside). */
function mediaRanges(css, test) {
  const out = [];
  for (const m of css.matchAll(/@media([^{]*)\{/g)) {
    if (!test.test(m[1])) continue;
    let depth = 1, i = m.index + m[0].length;
    for (; i < css.length && depth; i++) { if (css[i] === '{') depth++; else if (css[i] === '}') depth--; }
    out.push([m.index, i]);
  }
  return out;
}

/** A box-shadow layer that draws a line or a ring (no blur): the border checker's job (BR-05, BR-06). */
const shadowLine = (value) => value.split(/,(?![^(]*\))/).every((x) => { const n = x.replace(/rgba?\([^)]*\)|hsla?\([^)]*\)|#[0-9a-f]+|var\([^)]*\)|inset|transparent|currentcolor/gi, ' ').trim().split(/\s+/).filter(Boolean).map(parseFloat); if (n.length < 2 || n.some(Number.isNaN)) return false; const [, , blur = 0] = n; return blur === 0; });

function readShadow(K, value) {
  const jobs = [...value.matchAll(new RegExp(`--${K.p}-elevation-([a-z0-9]+)-shadow`, 'g'))].map((m) => m[1]);
  const raw = [...value.matchAll(new RegExp(`--${K.p}-color-(shadow-\\d|black-alpha-\\d+)`, 'g'))].map((m) => m[1]);
  const stripped = value.replace(new RegExp(`var\\(\\s*--${K.p}-elevation-[a-z0-9]+-shadow\\s*\\)`, 'g'), '').replace(/[\s,]/g, '');
  return { jobs, raw, handMade: stripped.length > 0 && !/^(none|inherit|initial|unset|revert)$/.test(value.trim()) };
}

const jobsIn = (K, value, part) => [...value.matchAll(new RegExp(`--${K.p}-elevation-([a-z0-9]+)-${part}`, 'g'))].map((m) => m[1]);
// The numbered levels before 23 Oct 2026, for a helpful message.
const OLD = { 0: 'page', 1: 'raised', 2: 'sticky', 3: 'floating', 4: 'modal' };
const hasBorder = (decls) => decls.some((d) => /^border(-(block|inline|top|right|bottom|left)(-(start|end))?)?(-width)?$/.test(d.prop) && !/^\s*(none|0|0px|hidden)\s*$/.test(d.value));
const removesBorder = (decls) => decls.find((d) => /^border(-width)?$/.test(d.prop) && /^\s*(none|0|0px|hidden)\s*$/.test(d.value));
const translucent = (v) => /rgba?\([^)]*,\s*0?\.\d+\s*\)|rgba?\([^)]*\/\s*0?\.\d+%?\s*\)|hsla?\([^)]*,\s*0?\.\d+\s*\)|#[0-9a-f]{6}[0-9a-e][0-9a-f]\b|#[0-9a-f]{3}[0-9a-e]\b|color-mix\([^)]*transparent/i.test(v);

export function lintText(K, text, file) {
  const ignored = new Set([...text.matchAll(/ds-lint-ignore:\s*([A-Z]{2}-\d{2}(?:[\s,]+[A-Z]{2}-\d{2})*)/g)].flatMap((m) => m[1].split(/[\s,]+/)));
  return lintCore(K, text, file).filter((x) => !ignored.has(x.rule));
}

function lintCore(K, text, file) {
  const out = [];
  const p = K.p;
  if (/generated by ds-engine|Tailwind v4 theme for ds/.test(text.slice(0, 300))) return out;
  const levelList = K.levels.filter((l) => K.shadowed.has(l)).join(', ');
  const layerList = [...K.layers].map((l) => `--${p}-layer-${l}`).join(', ');
  const cssSources = /\.(css|scss)$/.test(file) ? [{ css: text, start: 0 }] : [...text.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => ({ css: m[1], start: m.index + m[0].indexOf(m[1]) }));
  const rules = [];
  for (const src of cssSources) {
    const css = src.css.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '));
    const dark = mediaRanges(css, /prefers-color-scheme:\s*dark/);
    const forced = mediaRanges(css, /forced-colors:\s*active/); // system colours are the point there
    for (const m of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
      const selector = m[1].trim();
      if (selector.startsWith('@')) continue;
      const line = lineOf(text, src.start + m.index + m[1].length);
      const decls = parseDecls(m[2], line);
      if (forced.some(([a, b]) => m.index > a && m.index < b)) { rules.push({ selector, line, decls: decls.filter((d) => d.prop.startsWith('--')), dark: false }); continue; }
      rules.push({ selector, line, decls, dark: dark.some(([a, b]) => m.index > a && m.index < b) || DARK_SEL.test(selector) });
    }
  }
  // The shadow each selector has at rest, to compare hover and press with.
  const base = new Map();
  for (const r of rules) {
    if (HOVER.test(r.selector) || FOCUS.test(r.selector)) continue;
    for (const s of r.selector.split(',')) for (const d of r.decls) if (d.prop === 'box-shadow') base.set(s.replace(/\s+/g, ' ').trim(), d.value);
  }
  const order = (job) => K.levels.indexOf(job);
  for (const r of rules) {
    const at0 = { file, where: r.selector.slice(0, 60) };
    const shadowJobs = [], surfaceJobs = [];
    let bgRole = null;
    for (const d of r.decls) {
      const at = { ...at0, line: d.line };
      if (d.prop.startsWith('--')) {
        if (new RegExp(`^--${p}-(elevation|layer)-`).test(d.prop)) out.push({ ...at, rule: 'ER-10', level: 'error', message: `${d.prop} is redefined in app code.`, fix: 'Add a product layer in the engine config (elevation.layers) and build; levels are computed.' });
        continue;
      }
      if (d.prop === 'box-shadow') {
        if (shadowLine(d.value) && !readShadow(K, d.value).jobs.length) continue; // a line or ring: the border checker's job
        const s = readShadow(K, d.value);
        for (const j of s.jobs) if (!K.known.has(j)) out.push({ ...at, rule: 'ER-01', level: 'error', message: `--${p}-elevation-${j}-shadow is not a level in this system${OLD[j] ? ' (levels are named by job now)' : ''}.`, fix: OLD[j] ? `Use --${p}-elevation-${OLD[j]}-shadow — or the class .${p}-${OLD[j]}.` : `Use a level: ${levelList}.` });
        if (s.raw.length) out.push({ ...at, rule: 'ER-02', level: 'error', message: `box-shadow: ${d.value} builds a shadow from --${p}-color-${s.raw[0]}.`, fix: `Pick the level's shadow: var(--${p}-elevation-<job>-shadow) (${levelList}).` });
        else if (s.handMade) out.push({ ...at, rule: 'ER-01', level: 'error', message: `box-shadow: ${d.value} is hand-made — it belongs to no level.`, fix: `Use the level's shadow: var(--${p}-elevation-<job>-shadow) (${levelList}) — or the class .${p}-<job>.` });
        shadowJobs.push(...s.jobs.filter((j) => K.known.has(j)));
        if (r.dark && !/^\s*none\s*$/.test(d.value)) out.push({ ...at, rule: 'ER-07', level: 'error', message: `${r.selector.trim()} sets a shadow for dark mode.`, fix: 'Remove it: the level tokens switch for Dark by themselves, and height there comes from lighter surfaces.' });
      }
      for (const mm of d.value.matchAll(new RegExp(`--${p}-elevation-([a-z0-9]+)-(surface|border|scrim)`, 'g'))) if (!K.known.has(mm[1])) out.push({ ...at, rule: 'ER-01', level: 'error', message: `--${p}-elevation-${mm[1]}-${mm[2]} is not a level in this system${OLD[mm[1]] ? ' (levels are named by job now)' : ''}.`, fix: OLD[mm[1]] ? `Use --${p}-elevation-${OLD[mm[1]] === 'modal' && mm[2] === 'scrim' ? 'modal' : OLD[mm[1]]}-${mm[2]}.` : `Use a level: ${K.levels.join(', ')}.` });
      if (/^(-webkit-)?filter$/.test(d.prop) && /drop-shadow\(/.test(d.value)) out.push({ ...at, rule: 'ER-01', level: 'error', message: `${d.prop}: ${d.value} draws a shadow outside the levels.`, fix: `Use box-shadow: var(--${p}-elevation-<job>-shadow).` });
      if (/^(-webkit-)?backdrop-filter$/.test(d.prop) && !/^\s*none\s*$/.test(d.value)) out.push({ ...at, rule: 'ER-09', level: 'error', message: `${d.prop}: ${d.value} — a see-through surface: text contrast depends on what scrolls behind it.`, fix: `Use an opaque level surface (var(--${p}-elevation-floating-surface)).` });
      if (/^background(-color)?$/.test(d.prop)) {
        surfaceJobs.push(...jobsIn(K, d.value, 'surface'));
        bgRole = new RegExp(`--${p}-color-(bg-[a-z-]+)`).exec(d.value)?.[1] ?? bgRole;
        if (r.dark && (jobsIn(K, d.value, 'surface').length || new RegExp(`--${p}-color-bg-surface`).test(d.value))) out.push({ ...at, rule: 'ER-07', level: 'error', message: `${r.selector.trim()} swaps a level surface for dark mode.`, fix: 'Remove it: the surfaces switch for Dark by themselves (each level lighter than the one below).' });
      }
      if (d.prop === 'z-index') {
        const v = d.value.trim();
        const lay = new RegExp(`^var\\(\\s*--${p}-layer-([a-z-]+)\\s*\\)$`).exec(v);
        if (lay) { if (!K.layers.has(lay[1])) out.push({ ...at, rule: 'ER-05', level: 'error', message: `--${p}-layer-${lay[1]} is not a layer in this system.`, fix: `Use ${layerList} — or add a product layer (elevation.layers).` }); }
        else if (/^-?\d+$/.test(v) && !K.localZ.has(+v)) out.push({ ...at, rule: 'ER-05', level: 'error', message: `z-index: ${v} is a stray number${+v >= 300 ? ` — it races the layers (a dialog is ${K.c.layers.find((l) => l.name === 'layer.modal')?.value})` : ''}.`, fix: `Use a layer: ${layerList}${/popover|menu|dropdown|tooltip/.test(r.selector) ? ' — or open it as a popover (top layer, never clipped)' : ''}. Raw ${[...K.localZ].join(', ')} only for order inside one component.` });
        else if (!/^(auto|inherit|initial|unset|revert|-?\d+)$/.test(v)) out.push({ ...at, rule: 'ER-05', level: 'error', message: `z-index: ${v} is not a layer.`, fix: `Use ${layerList}.` });
      }
      if (/::backdrop/.test(r.selector) && /^background(-color)?$/.test(d.prop) && !new RegExp(`--${p}-elevation-modal-scrim`).test(d.value)) out.push({ ...at, rule: 'ER-06', level: 'error', message: `${r.selector.trim()} draws its own scrim (${d.value}).`, fix: `background: var(--${p}-elevation-modal-scrim) — or the class .${p}-modal, which sets it.` });
    }
    const lvls = [...new Set([...shadowJobs, ...surfaceJobs])];
    // ER-03: one level per rule — the shadow goes on its own level's surface.
    if (shadowJobs.length && surfaceJobs.length && surfaceJobs.some((s) => !shadowJobs.includes(s))) out.push({ ...at0, line: r.line, rule: 'ER-03', level: 'error', message: `${r.selector.trim()} mixes levels: the ${shadowJobs[0]} shadow on the ${surfaceJobs.find((s) => !shadowJobs.includes(s))} surface.`, fix: `Take one level: .${p}-${shadowJobs[0]} (or its surface, var(--${p}-elevation-${shadowJobs[0]}-surface)).` });
    else if (shadowJobs.length && !surfaceJobs.length && bgRole && K.surfaceRole[shadowJobs[0]] && `color.${bgRole.replace('-', '.')}` !== K.surfaceRole[shadowJobs[0]] && !HOVER.test(r.selector)) out.push({ ...at0, line: r.line, rule: 'ER-03', level: 'warning', message: `${r.selector.trim()} puts the ${shadowJobs[0]} shadow on --${p}-color-${bgRole}, not the ${shadowJobs[0]} surface (${K.surfaceRole[shadowJobs[0]]}).`, fix: `Use var(--${p}-elevation-${shadowJobs[0]}-surface) or .${p}-${shadowJobs[0]}.` });
    // ER-04: whatever floats keeps its edge.
    const floats = lvls.filter((j) => K.floating.has(j));
    if (floats.length && !hasBorder(r.decls) && !HOVER.test(r.selector) && !FOCUS.test(r.selector)) out.push({ ...at0, line: r.line, rule: 'ER-04', level: 'error', message: `${r.selector.trim()} floats (${floats[0]}) with no edge — forced colours remove its shadow and Dark barely shows it.`, fix: `border: var(--${p}-border-width-line) solid var(--${p}-elevation-${floats[0]}-border) — or the class .${p}-${floats[0]}.` });
    if (lvls.includes('sticky') && !hasBorder(r.decls) && !HOVER.test(r.selector)) out.push({ ...at0, line: r.line, rule: 'ER-04', level: 'warning', message: `${r.selector.trim()} is a sticky bar with no line toward the content.`, fix: `border-block-end: var(--${p}-border-width-line) solid var(--${p}-elevation-sticky-border) — or .${p}-sticky.` });
    const off = removesBorder(r.decls);
    if (off && new RegExp(`\\.${p}-(${[...K.floating].join('|')})(?![\\w-])`).test(r.selector)) out.push({ ...at0, line: off.line, rule: 'ER-04', level: 'error', message: `${r.selector.trim()} removes the edge of a floating level (${off.prop}: ${off.value}).`, fix: 'Keep it: the edge is what shows in forced colours and Dark.' });
    // ER-09: floating and modal surfaces stay opaque.
    if (floats.length || lvls.includes('modal')) {
      const tb = r.decls.find((d) => /^background(-color)?$/.test(d.prop) && translucent(d.value));
      if (tb) out.push({ ...at0, line: tb.line, rule: 'ER-09', level: 'error', message: `${r.selector.trim()} has a see-through background (${tb.value}).`, fix: `Use the opaque level surface var(--${p}-elevation-${floats[0] ?? 'modal'}-surface).` });
      const op = r.decls.find((d) => d.prop === 'opacity' && parseFloat(d.value) < 1);
      if (op && !/\[data-(state|closing)|:not\(:popover-open\)|@starting-style|closed/.test(r.selector)) out.push({ ...at0, line: op.line, rule: 'ER-09', level: 'warning', message: `${r.selector.trim()} makes a floating surface see-through (opacity: ${op.value}).`, fix: 'Keep it opaque at rest; fade only while it opens or closes.' });
    }
    // ER-08: hover and press never lift alone; press goes down.
    const hoverSel = r.selector.split(',').map((s) => s.trim()).find((s) => HOVER.test(s));
    if (hoverSel) {
      const sh = r.decls.find((d) => d.prop === 'box-shadow');
      const other = r.decls.some((d) => /^(background|background-color|border|border-color|border-[a-z-]*color|outline|outline-color|color|text-decoration|text-decoration-line)$/.test(d.prop));
      if (sh && !other) out.push({ ...at0, line: sh.line, rule: 'ER-08', level: 'warning', message: `${hoverSel} shows ${/active/.test(hoverSel) ? 'press' : 'hover'} by shadow alone — removed in forced colours, barely visible in Dark.`, fix: `Change the fill too (var(--${p}-color-bg-surface-hover)) or a border colour.` });
      if (sh && /:active/.test(hoverSel)) {
        const was = base.get(hoverSel.replace(HOVER, '').replace(/\s+/g, ' ').trim());
        const now = readShadow(K, sh.value).jobs[0], rest = was ? readShadow(K, was).jobs[0] : null;
        if (now && rest && order(now) > order(rest)) out.push({ ...at0, line: sh.line, rule: 'ER-08', level: 'warning', message: `${hoverSel} lifts on press (${rest} → ${now}).`, fix: `Press goes back down: var(--${p}-elevation-${rest}-shadow) or lower.` });
      }
    }
  }
  // Inline styles: the tag and classes stand in for the selector.
  for (const m of text.matchAll(/<([a-zA-Z][a-zA-Z0-9-]*)([^>]*?)\sstyle\s*=\s*"([^"]*)"/g)) {
    const at = { file, line: lineOf(text, m.index), where: 'inline style' };
    const decls = parseDecls(m[3], at.line);
    for (const d of decls) {
      if (new RegExp(`^--${p}-(elevation|layer)-`).test(d.prop)) out.push({ ...at, rule: 'ER-10', level: 'error', message: `${d.prop} is redefined inline.`, fix: 'Change the engine config and build.' });
      if (d.prop === 'box-shadow' && !shadowLine(d.value)) { const s = readShadow(K, d.value); if (s.raw.length) out.push({ ...at, rule: 'ER-02', level: 'error', message: `<${m[1]}> builds a shadow from --${p}-color-${s.raw[0]}.`, fix: 'Pick the level\'s shadow.' }); else if (s.handMade) out.push({ ...at, rule: 'ER-01', level: 'error', message: `<${m[1]}> has a hand-made shadow inline (${d.value}).`, fix: `Use var(--${p}-elevation-<job>-shadow) or .${p}-<job>.` }); }
      if (d.prop === 'z-index' && /^-?\d+$/.test(d.value.trim()) && !K.localZ.has(+d.value.trim())) out.push({ ...at, rule: 'ER-05', level: 'error', message: `<${m[1]}> has z-index: ${d.value} inline.`, fix: `Use a layer: ${layerList}.` });
      if (/^(-webkit-)?backdrop-filter$/.test(d.prop) && !/none/.test(d.value)) out.push({ ...at, rule: 'ER-09', level: 'error', message: `<${m[1]}> has ${d.prop} inline — a see-through surface.`, fix: 'Use an opaque level surface.' });
    }
    const cls = /class(?:Name)?=["']([^"']*)/.exec(m[2])?.[1] ?? '';
    const off = removesBorder(decls);
    if (off && new RegExp(`(^|\\s)${p}-(${[...K.floating].join('|')})(\\s|$)`).test(cls)) out.push({ ...at, rule: 'ER-04', level: 'error', message: `<${m[1]} class="${cls}"> removes its edge inline (${off.prop}: ${off.value}).`, fix: 'Keep the edge of a floating level.' });
  }
  // Dialogs in markup (style, script and comments blanked out, so prose about <dialog> isn't read as a tag).
  const markup = text.replace(/<(style|script)\b[\s\S]*?<\/\1>|<!--[\s\S]*?-->|\/\*[\s\S]*?\*\//g, (x) => x.replace(/[^\n]/g, ' '));
  for (const m of markup.matchAll(/<dialog\b([^>]*)>/g)) {
    const at = { file, line: lineOf(text, m.index), where: '<dialog>' };
    if (/(^|\s)open(\s|=|$)/.test(m[1])) out.push({ ...at, rule: 'ER-06', level: 'error', message: '<dialog open> opens without the top layer, the scrim or an inert page — Tab walks out of it.', fix: 'Leave out open and call dialog.showModal() (dialog.show() for a non-modal panel, which then is floating, not modal).' });
    if (!/aria-label(ledby)?=/.test(m[1])) out.push({ ...at, rule: 'ER-06', level: 'warning', message: '<dialog> without a label — a screen reader announces "dialog" and nothing else.', fix: 'aria-labelledby="<id of its heading>".' });
  }
  for (const m of markup.matchAll(/<([a-z][a-z0-9]*)\b([^>]*\brole=["']dialog["'][^>]*)>/g)) {
    const at = { file, line: lineOf(text, m.index), where: `<${m[1]} role="dialog">` };
    const modal = /aria-modal=["']?(true|\{true\})/.test(m[2]);
    if (modal && !new RegExp(`class(Name)?=["'][^"']*\\b${p}-scrim\\b`).test(text) && !/\binert\b/.test(text)) out.push({ ...at, rule: 'ER-06', level: 'error', message: 'A modal dialog built without <dialog>, with no scrim and no inert page behind it.', fix: `Use <dialog> + showModal(); or put a .${p}-scrim before it, make the page inert, move focus in, hold it and return it on close.` });
    if (!modal) out.push({ ...at, rule: 'ER-06', level: 'warning', message: 'role="dialog" without aria-modal: if it blocks the page, screen readers aren\'t told.', fix: 'aria-modal="true" for a modal (with the scrim and inert page), or no dialog role for a non-blocking panel.' });
  }
  if (/<dialog\b/.test(text) && /\.show\(\s*\)/.test(text) && !/\.showModal\(/.test(text)) out.push({ file, line: lineOf(text, text.search(/\.show\(\s*\)/)), where: 'script', rule: 'ER-06', level: 'warning', message: 'dialog.show() opens it without the top layer, the scrim or an inert page.', fix: 'dialog.showModal() for anything that must be answered.' });
  // Class lists: Tailwind shadow, z-index and backdrop utilities.
  const component = /\.(jsx|tsx|vue|svelte)$/.test(file);
  const classLists = component
    ? [...text.matchAll(/(["'`])((?:(?!\1)[^\\\n])*)\1/g)].filter((m) => /(^|\s|:)(-?z-|shadow|drop-shadow|backdrop|bg-)/.test(m[2]) && !/^[./@]|\s=>\s|^https?:/.test(m[2])).map((m) => ({ index: m.index, list: m[2] }))
    : [...text.matchAll(/class\s*=\s*["']([^"']*)["']/g)].map((m) => ({ index: m.index, list: m[1] }));
  for (const m of classLists) {
    const line = lineOf(text, m.index);
    const all = m.list.split(/\s+/).filter(Boolean);
    const bare = all.map((c) => c.replace(/^([a-z0-9@[\]_&=-]+:)+/, '').replace(/^!/, ''));
    const lv = bare.map((c) => /^shadow-([a-z]+)$/.exec(c)?.[1]).filter((j) => j && K.known.has(j));
    const floatsTw = lv.filter((j) => K.floating.has(j));
    for (const [i, c] of bare.entries()) {
      const raw = all[i], w = { file, line, where: `class "${raw}"` };
      if (/^shadow(-(2xs|xs|sm|md|lg|xl|2xl|inner))?$/.test(c) || /^shadow-\[/.test(c) || /^shadow-\(/.test(c) && !new RegExp(`--${p}-elevation-`).test(c)) out.push({ ...w, rule: 'ER-01', level: 'error', message: `${raw} — Tailwind's own shadow, outside the levels.`, fix: `Use shadow-<level> (${levelList}) or the class ${p}-<level>.` });
      else if (/^shadow-([a-z]+)(-\d+)?(\/\d+)?$/.test(c) && !K.known.has(c.slice(7)) && c !== 'shadow-none') out.push({ ...w, rule: 'ER-02', level: 'error', message: `${raw} colours a shadow by hand.`, fix: 'The level\'s shadow carries its colour (shadow-floating …).' });
      if (/^(drop-shadow|inset-shadow)(-|$)/.test(c) && c !== 'drop-shadow-none') out.push({ ...w, rule: 'ER-01', level: 'error', message: `${raw} draws a shadow outside the levels.`, fix: `Use shadow-<level>.` });
      if (/^-?z-(\d+|\[[^\]]+\])$/.test(c)) { const n = +c.replace(/^(-?)z-\[?(-?\d+)\]?$/, '$1$2'); if (Number.isNaN(n) || !K.localZ.has(n)) out.push({ ...w, rule: 'ER-05', level: 'error', message: `${raw} is a stray z-index.`, fix: `Use z-(--${p}-layer-<job>) (${[...K.layers].join(', ')}).` }); }
      if (/^z-\((--[a-z0-9-]+)\)$/.test(c) && !new RegExp(`^z-\\(--${p}-layer-(${[...K.layers].join('|')})\\)$`).test(c)) out.push({ ...w, rule: 'ER-05', level: 'error', message: `${raw} is not a layer.`, fix: `Use z-(--${p}-layer-<job>) (${[...K.layers].join(', ')}).` });
      if (/^backdrop-(blur|filter|opacity|saturate|brightness)/.test(c) && !/-none$/.test(c)) out.push({ ...w, rule: 'ER-09', level: 'error', message: `${raw} makes a see-through surface: text contrast depends on what scrolls behind it.`, fix: 'Use the opaque level surface (bg-elevation-floating-surface).' });
      if (floatsTw.length && /^bg-[a-z0-9-]+\/\d+$/.test(c)) out.push({ ...w, rule: 'ER-09', level: 'error', message: `${raw} — a translucent background on a ${floatsTw[0]} surface.`, fix: `Use bg-elevation-${floatsTw[0]}-surface.` });
    }
    if (floatsTw.length && !bare.some((c) => /^border(-[xytrblse]{1,2})?(-(line|control))?$/.test(c) || /^border-elevation-[a-z]+-border$/.test(c)) && !all.some((c) => new RegExp(`^${p}-(${[...K.floating].join('|')})$`).test(c))) out.push({ file, line, where: `class "${m.list.slice(0, 50)}"`, rule: 'ER-04', level: 'error', message: `shadow-${floatsTw[0]} with no edge.`, fix: `Add border-line border-elevation-${floatsTw[0]}-border — or use the class ${p}-${floatsTw[0]}.` });
    const hoverShadow = all.find((c) => /(^|:)(hover|active):shadow-/.test(c));
    if (hoverShadow && !all.some((c) => /(^|:)(hover|active):(bg-|border-|outline|underline|text-)/.test(c))) out.push({ file, line, where: `class "${hoverShadow}"`, rule: 'ER-08', level: 'warning', message: `${hoverShadow} shows hover by shadow alone.`, fix: 'Add hover:bg-surface-hover (or a border colour) beside it.' });
  }
  return out;
}

const CHECKED = /\.(css|scss|html|htm|jsx|tsx|vue|svelte)$/;
export function expand(paths) {
  const out = [];
  const walk = (p) => {
    const st = fs.statSync(p);
    if (st.isDirectory()) { for (const n of fs.readdirSync(p)) if (!/^(node_modules|dist|build|out|\..*)$/.test(n)) walk(path.join(p, n)); }
    else if (CHECKED.test(p)) out.push(p);
  };
  for (const p of paths) walk(p);
  return out;
}

export function lintFiles(files, contractFile) {
  const K = loadContract(contractFile);
  return expand(files).flatMap((f) => lintText(K, fs.readFileSync(f, 'utf8'), f));
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('elevation-lint.js')) {
  const args = process.argv.slice(2);
  const ci = args.indexOf('--contract');
  const contract = ci >= 0 ? args.splice(ci, 2)[1] : path.join(HERE, '../../out/default/ai/elevation.contract.json');
  const asJson = args.includes('--json');
  const files = args.filter((a) => a !== '--json');
  if (!fs.existsSync(contract)) {
    console.error(`No elevation contract at ${contract}. Run the build first (npm run build in the engine folder), or point --contract at the elevation.contract.json you ship.`);
    process.exit(2);
  }
  const findings = lintFiles(files, contract);
  if (asJson) console.log(JSON.stringify(findings, null, 2));
  else {
    for (const x of findings) console.log(`${x.level === 'error' ? '✕' : '!'} ${x.file}:${x.line}  ${x.rule}  ${x.message}  → ${x.fix}`);
    const e = findings.filter((x) => x.level === 'error').length;
    console.log(`\n${expand(files).length} file(s) · ${e} error(s) · ${findings.length - e} warning(s)`);
  }
  process.exit(findings.some((x) => x.level === 'error') ? 1 : 0);
}
